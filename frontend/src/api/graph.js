import service, { requestWithRetry } from './index.js'
export { buildOntologyFormData } from './ontologyFormData.js'

/**
 * 获取可用的 persona packs 列表
 * @returns {Promise}
 */
export function listPersonaPacks() {
  return service({
    url: '/api/graph/persona-packs',
    method: 'get'
  })
}

/**
 * 生成本体（上传文档和模拟需求）
 * @param {FormData} formData
 * @returns {Promise}
 */
export function generateOntology(formData) {
  return requestWithRetry(() =>
    service({
      url: '/api/graph/ontology/generate',
      method: 'post',
      data: formData,
      headers: {
        'Content-Type': 'multipart/form-data'
      }
    })
  )
}

/**
 * 构建图谱
 * @param {Object} data
 * @returns {Promise}
 */
export function buildGraph(data) {
  return requestWithRetry(() =>
    service({
      url: '/api/graph/build',
      method: 'post',
      data
    })
  )
}

